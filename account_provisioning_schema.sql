-- Supabase SQL Editor：以管理員身分執行一次。
-- 只保存密碼雜湊，不保存明文密碼；service_role key 僅能放在 Streamlit Secrets。
-- 帳號申請：狀態、核准與拒絕連結的 token 雜湊、密碼雜湊與各階段時間。
create table if not exists public.account_requests (
    id bigint generated by default as identity primary key,
    email text not null,
    status text not null default 'pending'
        check (status in ('pending', 'approved', 'rejected', 'notification_failed')),
    approve_token_hash text,
    reject_token_hash text,
    password_hash text,
    created_at timestamptz not null default now(),
    token_expires_at timestamptz,
    decided_at timestamptz,
    approved_at timestamptz,
    activate_at timestamptz
);
-- 依 Email 查詢（不分大小寫）。
create index if not exists account_requests_email_idx on public.account_requests (lower(email));
-- 同一個 Email 同時只能有一筆審核中或已核准的申請。
create unique index if not exists account_requests_one_active_email_idx
    on public.account_requests (lower(email)) where status in ('pending', 'approved');
-- 依狀態與到期時間查詢。
create index if not exists account_requests_status_expiry_idx on public.account_requests (status, token_expires_at);
-- 開啟資料列權限，一般 API 金鑰無法直接讀取；網站用 service_role key 存取。
alter table public.account_requests enable row level security;
-- Email 必須是 3～254 字元、全小寫且前後沒有空白（先刪再建，可重複執行）。
alter table public.account_requests drop constraint if exists account_requests_email_length_check;
alter table public.account_requests add constraint account_requests_email_length_check
    check (length(email) between 3 and 254 and email = lower(btrim(email)));
